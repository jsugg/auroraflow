import { createHash } from 'node:crypto';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { beforeAll, describe, expect, it } from 'vitest';

type AttributionKind = 'refName' | 'commitMessage' | 'email' | 'label';

interface AttributionPatternsModule {
  readonly REF_NAME: string;
  readonly COMMIT_MESSAGE: string;
  readonly EMAIL: string;
  readonly LABEL: string;
  readonly ATTRIBUTION_PATTERNS: Readonly<Record<AttributionKind, RegExp>>;
  compileAttributionPattern(source: string): RegExp;
  findAttribution(kind: AttributionKind, value: string): string | null;
}

const PATTERNS_MODULE_URL = pathToFileURL(
  path.join(process.cwd(), 'scripts/attribution-patterns.mjs'),
).href;

// SHA-256 of each pattern string in the shared source; a mismatch means the vendored copy drifted
// from the definition the GitHub rulesets and local agent hooks enforce.
const SOURCE_PATTERN_DIGESTS: Readonly<
  Record<'REF_NAME' | 'COMMIT_MESSAGE' | 'EMAIL' | 'LABEL', string>
> = {
  REF_NAME: 'fc5182885eb186d722497ebb8288336c426fb5a38e188699a07ac21674cd9d11',
  COMMIT_MESSAGE: '820b259c44f4c1048e48a74dc7bcc45b185014ae27b5b407f6944f59a742611d',
  EMAIL: 'f65b6035d90fba033ca575c090a3de0730e7b82c3f173fb6b54c370b154baf2d',
  LABEL: 'd2e142fda7ece4e994913983b43b50d6b1c7a4c3434d375a118c493defbc977a',
};

// Golden vectors vendored verbatim from the shared source's GOLDEN table.
