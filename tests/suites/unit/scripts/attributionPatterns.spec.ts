// The shared source has no label vectors; these follow the owner rule that the banned words may
// not appear anywhere in a label, while ordinary Dependabot labels stay valid.
const LABEL_DENY = ['claude', 'needs-Codex-review', 'anthropic', 'openai-sync'] as const;
const LABEL_ALLOW = ['dependencies', 'github_actions', 'javascript', 'security'] as const;

let patterns: AttributionPatternsModule;

beforeAll(async () => {
  patterns = (await import(PATTERNS_MODULE_URL)) as AttributionPatternsModule;
});

function sha256(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

describe('attribution patterns', () => {
  it('vendors the shared pattern strings byte-identically', () => {
    expect({
      REF_NAME: sha256(patterns.REF_NAME),
      COMMIT_MESSAGE: sha256(patterns.COMMIT_MESSAGE),
      EMAIL: sha256(patterns.EMAIL),
      LABEL: sha256(patterns.LABEL),
    }).toEqual(SOURCE_PATTERN_DIGESTS);
  });

  it('translates leading inline flag groups into JavaScript RegExp flags', () => {
    expect(patterns.ATTRIBUTION_PATTERNS.refName.flags).toBe('i');
    expect(patterns.ATTRIBUTION_PATTERNS.commitMessage.flags).toBe('im');
    expect(patterns.ATTRIBUTION_PATTERNS.email.flags).toBe('i');
    expect(patterns.ATTRIBUTION_PATTERNS.label.flags).toBe('i');
    expect(patterns.compileAttributionPattern('^plain$').flags).toBe('');
    expect(patterns.ATTRIBUTION_PATTERNS.refName.source.startsWith('(?')).toBe(false);
    expect(() => patterns.compileAttributionPattern('(?s)x')).toThrow(/Unsupported inline/);
  });

  it.each(GOLDEN.refDeny)('denies tool-namespaced ref %j', (refName) => {
    expect(patterns.findAttribution('refName', refName)).not.toBeNull();
  });

  it.each(GOLDEN.refAllow)('allows subject-matter ref %j', (refName) => {
    expect(patterns.findAttribution('refName', refName)).toBeNull();
  });

  it.each(GOLDEN.msgDeny)('denies attributed commit message %j', (message) => {
    expect(patterns.findAttribution('commitMessage', message)).not.toBeNull();
  });

  it.each(GOLDEN.msgAllow)('allows subject-matter commit message %j', (message) => {
    expect(patterns.findAttribution('commitMessage', message)).toBeNull();
  });

  it.each(GOLDEN.emailDeny)('denies vendor email %j', (email) => {
    expect(patterns.findAttribution('email', email)).not.toBeNull();
  });

  it.each(GOLDEN.emailAllow)('allows email %j', (email) => {
    expect(patterns.findAttribution('email', email)).toBeNull();
  });

  it.each(LABEL_DENY)('denies label %j', (label) => {
    expect(patterns.findAttribution('label', label)).not.toBeNull();
  });

  it.each(LABEL_ALLOW)('allows label %j', (label) => {
    expect(patterns.findAttribution('label', label)).toBeNull();
  });

  it('rejects unknown field kinds instead of passing them', () => {
    expect(() => patterns.findAttribution('branch' as AttributionKind, 'main')).toThrow(
      /Unknown attribution field kind/,
    );
  });
});
